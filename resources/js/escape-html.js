// Экранирование данных перед вставкой в разметку через innerHTML.
// Имена работников, товаров и контрагентов приходят из БД и МойСклад — им нельзя доверять.
const ENTITIES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' };

window.escapeHtml = (value) => String(value ?? '').replace(/[&<>"']/g, (c) => ENTITIES[c]);
