<?php

use App\Support\ProductSearch;

/**
 * Поиск товара по части названия — зеркало tokenize()/fuzzyMatch() из product-picker.js:
 * фильтр «Все, где есть …» должен находить ровно то, что видно в выпадашке пикера.
 */
test('tokenize: нижний регистр, разделители, ё → е, латинские двойники → кириллица', function () {
    expect(ProductSearch::tokenize('Плитка из Кварцит 50xL, Ёлка/MIX'))
        ->toBe(['плитка', 'из', 'кварцит', '50хl', 'елка', 'мiх']);
});

test('tokenize: строка без букв и цифр — пустой список', function () {
    expect(ProductSearch::tokenize(' — / ,'))->toBe([]);
});

test('совпадение по части названия', function (string $name, string $query, bool $expected) {
    expect(ProductSearch::matches($name, $query))->toBe($expected);
})->with([
    'часть слова'                    => ['Плитка Кварцит 50хL', 'кварц', true],
    'регистр не важен'               => ['Плитка Кварцит 50хL', 'КВАРЦ', true],
    'несколько слов в любом порядке' => ['Плитка Кварцит 50хL', '50 квар плит', true],
    'середина слова'                 => ['Плитка Кварцит 50хL', 'арци', true],
    'латинская x вместо кириллицы'   => ['Плитка Кварцит 50хL', '50xl', true],
    'кириллица вместо латинской'     => ['Плитка 50xL', '50хl', true],
    'ё и е'                          => ['Плитка тёмная', 'темн', true],
    'одно слово не нашлось'          => ['Плитка Кварцит 50хL', 'кварц гранит', false],
    'слово не склеивается из двух'   => ['Плитка Кварцит', 'плиткакварц', false],
    'пустой запрос — подходит всё'   => ['Плитка', '', true],
]);
